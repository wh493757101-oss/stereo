def _own_prf(tp, fp, fn):
    precision = tp / (tp + fp) if (tp + fp) else 0.0
    recall = tp / (tp + fn) if (tp + fn) else 0.0
    f1 = (2 * precision * recall / (precision + recall)
          if (precision + recall) else 0.0)
    return {"precision": precision, "recall": recall, "f1": f1,
            "tp": tp, "fp": fp, "fn": fn}


def _own_candidate_counts(frames, rows_by_key):
    counts = dict.fromkeys(COUNTS_FIELDS, 0)
    cond_tp = [0] * 4
    cond_fp = [0] * 4
    cond_fn = [0] * 4
    cond_correct = 0
    e2e_tp = [0] * 4
    e2e_fp = [0] * 4
    e2e_fn = [0] * 4
    confusion = [[0] * 4 for _ in range(4)]
    ious = []
    for frame in frames:
        if frame["frame_error"]:
            counts["failed_frames"] += 1
            continue
        counts["frames"] += 1
        gt_classes = {g["gt_id"]: g["class_id"] for g in frame["gt"]}
        counts["gt_instances"] += len(gt_classes)
        counts["predictions"] += len(frame["predictions"])
        counts["matched"] += len(frame["matches"])
        ious.extend(m[2] for m in frame["matches"])
        matched_gt = {m[0] for m in frame["matches"]}
        matched_pred = {m[1] for m in frame["matches"]}
        for gt_id, pred_id, _iou in frame["matches"]:
            true_class = gt_classes[gt_id]
            row = rows_by_key.get((frame["frame_id"], pred_id))
            if row is None or row["status"] != "valid":
                counts["unclassified_matched"] += 1
                e2e_fn[true_class] += 1
                continue
            pred_class = row["predicted_class"]
            confusion[true_class][pred_class] += 1
            if pred_class == true_class:
                cond_tp[true_class] += 1
                cond_correct += 1
                e2e_tp[true_class] += 1
            else:
                cond_fn[true_class] += 1
                cond_fp[pred_class] += 1
                e2e_fn[true_class] += 1
                e2e_fp[pred_class] += 1
        for gt_id, class_id in gt_classes.items():
            if gt_id not in matched_gt:
                e2e_fn[class_id] += 1
        for pred in frame["predictions"]:
            if pred["pred_instance_id"] not in matched_pred:
                row = rows_by_key.get((frame["frame_id"],
                                       pred["pred_instance_id"]))
                if row is not None and row["status"] == "valid":
                    e2e_fp[row["predicted_class"]] += 1
    counts["evaluated_frames"] = counts["frames"] - counts["failed_frames"]
    counts["missed_gt"] = counts["gt_instances"] - counts["matched"]
    counts["unmatched_predictions"] = (counts["predictions"]
                                       - counts["matched"])
    conditional_samples = sum(cond_tp) + sum(cond_fn)
    return {
        "counts": counts,
        "detection": _own_prf(counts["matched"],
                              counts["unmatched_predictions"],
                              counts["missed_gt"]),
        "matched_iou": {
            "n": len(ious),
            "mean": (sum(ious) / len(ious)) if ious else 0.0,
            "min": min(ious) if ious else 0.0,
            "max": max(ious) if ious else 0.0,
        },
        "conditional": {
            "samples": conditional_samples,
            "accuracy": (cond_correct / conditional_samples)
            if conditional_samples else 0.0,
            "macro_f1": sum(_own_prf(cond_tp[i], cond_fp[i],
                                     cond_fn[i])["f1"]
                            for i in range(4)) / 4,
            "confusion_matrix": confusion,
            "per_class": {name: _own_prf(cond_tp[i], cond_fp[i],
                                         cond_fn[i])
                          for i, name in enumerate(CLASS_NAMES)},
        },
        "end_to_end": {
            "macro_f1": sum(_own_prf(e2e_tp[i], e2e_fp[i],
                                     e2e_fn[i])["f1"]
                            for i in range(4)) / 4,
            "per_class": {name: _own_prf(e2e_tp[i], e2e_fp[i],
                                         e2e_fn[i])
                          for i, name in enumerate(CLASS_NAMES)},
        },
    }


def _own_paired(frames, rows_other, rows_base):
    fixed = broke = both_correct = both_wrong = 0
    for frame in frames:
        if frame["frame_error"]:
            continue
        gt_classes = {g["gt_id"]: g["class_id"] for g in frame["gt"]}
        matched_by_gt = {m[0]: m[1] for m in frame["matches"]}
        for gt_id, true_class in gt_classes.items():
            pred_id = matched_by_gt.get(gt_id)
            other_row = rows_other.get((frame["frame_id"], pred_id))
            base_row = rows_base.get((frame["frame_id"], pred_id))

            def _correct(row):
                return bool(row is not None and row["status"] == "valid"
                            and row["predicted_class"] == true_class)

            other_ok = _correct(other_row)
            base_ok = _correct(base_row)
            if other_ok and base_ok:
                both_correct += 1
            elif not other_ok and not base_ok:
                both_wrong += 1
            elif other_ok:
                fixed += 1
            else:
                broke += 1
    return {"fixed": fixed, "broke": broke,
            "both_correct": both_correct, "both_wrong": both_wrong}


def _own_per_frame_correctness(frames, rows_by_key):
    values, groups = [], []
    for frame in frames:
        if frame["frame_error"]:
            continue
        gt_classes = {g["gt_id"]: g["class_id"] for g in frame["gt"]}
        matched_by_gt = {m[0]: m[1] for m in frame["matches"]}
        for gt_id, true_class in gt_classes.items():
            row = rows_by_key.get((frame["frame_id"],
                                   matched_by_gt.get(gt_id)))
            ok = bool(row is not None and row["status"] == "valid"
                      and row["predicted_class"] == true_class)
            values.append(1.0 if ok else 0.0)
            groups.append(frame["group"])
    return values, groups


def _own_cluster_bootstrap(values_a, values_b, groups):
    """Test-local implementation of the frozen paired cluster bootstrap
    (seed 2026, 2000 whole-group draws with replacement, percentile
    2.5%/97.5%)."""
    deltas = [a - b for a, b in zip(values_a, values_b)]
    unique = sorted(set(groups))
    indices = {group: [i for i, g in enumerate(groups) if g == group]
               for group in unique}
    rng = random.Random(2026)
    means = []
    for _ in range(2000):
        sample = [i for _draw in unique
                  for i in indices[unique[rng.randrange(len(unique))]]]
        means.append(sum(deltas[i] for i in sample) / len(sample))
    means.sort()
    return {"delta_mean": sum(deltas) / len(deltas),
            "ci_low": means[int(0.025 * len(means))],
            "ci_high": means[int(0.975 * len(means)) - 1],
            "resamples": 2000, "clusters": len(unique), "seed": 2026}


def _own_e2e_macro_f1(frames, rows_by_key):
    block = _own_candidate_counts(frames, rows_by_key)
    return block["end_to_end"]["macro_f1"]


def _own_e2e_bootstrap(frames, rows_other, rows_base):
    """Test-local implementation of the frozen end-to-end Macro-F1 delta
    bootstrap, including the declared full-sample counts of both sides."""
    groups = sorted({frame["group"] for frame in frames})
    by_group = {group: [frame for frame in frames
                        if frame["group"] == group] for group in groups}
    full_other = _own_candidate_counts(frames, rows_other)
    full_base = _own_candidate_counts(frames, rows_base)
    rng = random.Random(2026)
    deltas = []
    for _ in range(2000):
        draws = [groups[rng.randrange(len(groups))] for _ in groups]
        selected = [frame for group in draws for frame in by_group[group]]
        deltas.append(_own_e2e_macro_f1(selected, rows_other)
                      - _own_e2e_macro_f1(selected, rows_base))
    deltas.sort()
    return {
        "point_estimate": full_other["end_to_end"]["macro_f1"]
        - full_base["end_to_end"]["macro_f1"],
        "ci_low": deltas[int(0.025 * len(deltas))],
        "ci_high": deltas[int(0.975 * len(deltas)) - 1],
        "resamples": 2000, "valid_resamples": len(deltas),
        "clusters": len(groups), "seed": 2026,
        "e4_macro_f1": full_other["end_to_end"]["macro_f1"],
        "e1_macro_f1": full_base["end_to_end"]["macro_f1"],
        "counts_e4": full_other["counts"],
        "counts_e1": full_base["counts"],
    }


def _own_expected_summary():
    """The complete expected Layer B summary of the synthetic world,
    computed entirely by the test-local algorithms above."""
    rows = _world_predictions()
    views = {cid: {} for cid in CANDIDATE_IDS}
    for row in rows:
        views[row["candidate_id"]][(row["frame_id"],
                                    row["pred_instance_id"])] = row
    summary = {"metrics_by_candidate": {}, "per_group": {}, "paired": {},
               "bootstrap": {}, "fallback_all_predictions": {},
               "frames": len(WORLD_FRAMES), "failed_frames": [],
               "candidates": list(CANDIDATE_IDS)}

    def _block(frames, candidate_id):
        block = _own_candidate_counts(frames, views[candidate_id])
        return {
            "counts": block["counts"],
            "detection": block["detection"],
            "matched_iou": block["matched_iou"],
            "conditional_classification": {
                "samples": block["conditional"]["samples"],
                "accuracy": block["conditional"]["accuracy"],
                "macro_f1": block["conditional"]["macro_f1"],
                "confusion_matrix": block["conditional"][
                    "confusion_matrix"],
                "per_class": block["conditional"]["per_class"],
            },
            "end_to_end": block["end_to_end"],
        }

    groups = sorted({frame["group"] for frame in WORLD_FRAMES})
    for candidate_id in CANDIDATE_IDS:
        summary["metrics_by_candidate"][candidate_id] = _block(
            WORLD_FRAMES, candidate_id)
        summary["per_group"][candidate_id] = {
            group: _block([frame for frame in WORLD_FRAMES
                           if frame["group"] == group], candidate_id)
            for group in groups}
        rows_of = views[candidate_id]
        predictions_count = len(rows_of)
        fallback_rows = [row for row in rows_of.values()
                         if row["used_fallback"]]
        reasons = {}
        for row in fallback_rows:
            reasons[row["fallback_reason"]] = \
                reasons.get(row["fallback_reason"], 0) + 1
        summary["fallback_all_predictions"][candidate_id] = {
            "predictions": predictions_count,
            "valid": sum(1 for row in rows_of.values()
                         if row["status"] == "valid"),
            "failed": sum(1 for row in rows_of.values()
                          if row["status"] != "valid"),
            "used_fallback": len(fallback_rows),
            "fallback_ratio": (len(fallback_rows) / predictions_count
                               if predictions_count else 0.0),
            "reasons": reasons,
        }
    for candidate_id in CANDIDATE_IDS:
        if candidate_id == "R0":
            continue
        family = ("linear_local"
                  if candidate_id.startswith("linear_local")
                  else "conditional")
        seed = candidate_id.rsplit("_s", 1)[1]
        # the source's declared pair labels use the SHORT base suffix
        # (_minus_R0 / _minus_RC), not the full base candidate id
        for base_id, base_suffix in (("R0", "R0"),
                                     (f"{family}_RC_s{seed}", "RC")):
            label = f"{candidate_id}_minus_{base_suffix}"
            summary["paired"][label] = _own_paired(
                WORLD_FRAMES, views[candidate_id], views[base_id])
            summary["bootstrap"][f"end_to_end_macro_f1_{label}"] = \
                _own_e2e_bootstrap(WORLD_FRAMES, views[candidate_id],
                                   views[base_id])
            va, ga = _own_per_frame_correctness(WORLD_FRAMES,
                                                views[candidate_id])
            vb, _gb = _own_per_frame_correctness(WORLD_FRAMES,
                                                 views[base_id])
            summary["bootstrap"][f"instance_correctness_{label}"] = \
                _own_cluster_bootstrap(va, vb, ga)
    return summary


