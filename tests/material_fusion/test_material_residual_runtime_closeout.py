# mapping, must each be a MISMATCH difference — never a silent skip.
# Every full-CLI case runs the REAL main() over an otherwise legal
# independent world copy, mutating exactly ONE summary factor.


class TestSummaryStructureGuards:
    def _run_structure_case(self, recompute_case, mutator, output_name,
                            fragment):
        """Mutate ONE summary factor, run the real main(), and assert the
        failure came from the target structural check — the authority
        chain, raw admission, the Layer A verdict and the output layout
        are all clean, so the only difference source is the guard."""
        _mutate_summary(recompute_case["case"], mutator)
        code, report = _run_case(recompute_case, output_name=output_name)
        assert code == 3, report["comparison"]["differences"][:5]
        assert report["status"] == "MISMATCH"
        assert report["authority"]["protocol_verified"] is True
        assert report["authority"]["csv_verified"] is True
        assert report["raw_problems"] == {}
        assert report["layer_a_record_verdict"]["status"] == "OK"
        assert _differences_contain(report, fragment)
        assert report["status"] != "PASSED"
        return report

    def test_per_group_extra_candidate_is_a_difference(
            self, recompute_case):
        def mutate(summary):
            summary["per_group"]["extra_candidate"] = {
                group: {} for group in summary["per_group"]["R0"]}

        self._run_structure_case(
            recompute_case, mutate, "pg_extra_candidate",
            "per_group.candidates")

    def test_paired_none_result_block_is_a_difference(
            self, recompute_case):
        label = "conditional_RCS_s2026_minus_R0"

        def mutate(summary):
            summary["paired"][label] = None

        self._run_structure_case(
            recompute_case, mutate, "paired_none", f"paired.{label}")

    def test_e2e_bootstrap_none_result_block_is_a_difference(
            self, recompute_case):
        label = "end_to_end_macro_f1_conditional_RCS_s2026_minus_R0"

        def mutate(summary):
            summary["bootstrap"][label] = None

        self._run_structure_case(
            recompute_case, mutate, "boot_e2e_none", f"bootstrap.{label}")

    def test_instance_bootstrap_none_result_block_is_a_difference(
            self, recompute_case):
        label = "instance_correctness_conditional_RCS_s2026_minus_R0"

        def mutate(summary):
            summary["bootstrap"][label] = None

        self._run_structure_case(
            recompute_case, mutate, "boot_inst_none", f"bootstrap.{label}")


