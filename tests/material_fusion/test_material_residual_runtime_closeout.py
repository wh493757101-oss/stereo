class TestBudgetResolution:
    def _config(self, whole_run=None, bench_budget=15):
        benchmark = {"frame_count": 2, "warmup_per_frame": 1,
                     "measured_per_frame": 1,
                     "budget_minutes": bench_budget}
        evaluation_budget = ({"whole_run_minutes": whole_run}
                             if whole_run is not None else {})
        return yaml.safe_load(yaml.safe_dump({
            "benchmark": benchmark,
            "evaluation_budget": evaluation_budget,
        }))

    def test_default_is_30_not_the_benchmark_15(self):
        config = self._config(whole_run=None, bench_budget=15)
        assert entry.resolve_evaluation_budget(config, None) == 30.0

    def test_evaluation_budget_wins_over_default(self):
        config = self._config(whole_run=45)
        assert entry.resolve_evaluation_budget(config, None) == 45.0

    def test_explicit_cli_override_wins(self):
        config = self._config(whole_run=45)
        assert entry.resolve_evaluation_budget(config, 10) == 10.0

    @pytest.mark.parametrize("bad", (0, -5, float("inf"), float("nan"),
                                     "abc"))
    def test_illegal_values_refused(self, bad):
        config = self._config(whole_run=30)
        with pytest.raises(ValueError):
            entry.resolve_evaluation_budget(config, bad)

    def test_config_level_none_refused(self):
        config = self._config(whole_run=None)
        config["evaluation_budget"]["whole_run_minutes"] = None
        with pytest.raises(ValueError):
            entry.resolve_evaluation_budget(config, None)

    def test_non_positive_config_refused(self):
        config = self._config(whole_run=0)
        with pytest.raises(ValueError):
            entry.resolve_evaluation_budget(config, None)

    def test_watch_requires_finite_positive(self):
        from scripts.eval_material_residual_pipeline import BudgetWatch

        with pytest.raises(ValueError):
            BudgetWatch(budget_minutes=float("inf"))


