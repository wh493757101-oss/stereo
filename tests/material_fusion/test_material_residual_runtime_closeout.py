class _GateOnlyTotalWatch:
    """A total-watch stand-in that only fires at the PARTIAL publish
    gate: it models a total budget that expires between boundary checks
    and pins the gate-before-publish ordering."""

    scope = "whole-evaluation budget"

    def check(self, stage: str) -> None:
        if stage == "benchmark PARTIAL publish gate":
            raise entry.BudgetExceeded(
                "the whole-evaluation budget is exhausted at the publish "
                "gate", watch_scope=self.scope)


