class _TimedEngine:
    """A synthetic benchmark engine: counts its calls and advances the
    shared fake clock by a fixed amount per call."""

    def __init__(self, advance, amount):
        import types

        self._advance = advance
        self._amount = amount
        self._types = types
        self.calls = 0

    def process_frame_detailed(self, left, right, *, sync_skew_ms=None,
                               already_rectified=False, frame_id=""):
        self.calls += 1
        self._advance(self._amount)
        return self._types.SimpleNamespace(
            instances=[], material_inputs=[],
            timings={"model_a_s": 0.0, "stereo_s": 0.0, "depth_s": 0.0,
                     "polar_s": 0.0, "model_b_s": 0.0, "total_s": 0.01})


